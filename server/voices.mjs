export function resolveVoice(name) {
  const key = String(name || '').trim();
  if (VOICE_MAP[key]) return VOICE_MAP[key];
  const mapped = LEGACY_VOICE[key];
  if (mapped && VOICE_MAP[mapped]) return VOICE_MAP[mapped];
  const byEdge = VOICES.find((v) => v.edge === key);
  if (byEdge) return byEdge;
  return VOICE_MAP.af_heart;
}

